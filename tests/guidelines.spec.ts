import { expect, test } from '@playwright/test'
import { CALIFORNIA_DISCLOSURE } from '../shared/reviewPolicy.mjs'

test('California guideline states its company authority and provides a usable live example', async ({ page }) => {
  await page.goto('./?guidelines')
  const rule = page.locator('#state-review')
  await expect(rule).toContainText(CALIFORNIA_DISCLOSURE)
  await expect(rule).toContainText('fictional ClearPath company policy')
  await expect(rule.getByRole('link')).toHaveAttribute('href', '?guidelines#state-review')
  const example = page.locator('#california-example')
  await expect(example).toContainText('Prepare correction')
  const download = example.getByRole('link', { name: 'Download California example · JPEG' })
  const result = await page.request.get((await download.getAttribute('href'))!)
  expect(result.ok()).toBe(true)
  expect(result.headers()['content-type']).toContain('image/jpeg')
  expect((await result.body()).length).toBeGreaterThan(10000)
})

test('guidelines are reachable from the walkthrough, link directly, and preserve review progress', async ({ page }) => {
  await page.goto('./?prepared')
  await page.getByRole('button', { name: 'Check submission', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Ready on the first pass' })).toBeVisible()
  await page.getByRole('button', { name: 'Review guidelines', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Review guidelines', exact: true })).toBeFocused()
  await expect(page.locator('.guidelines-checklist > li')).toHaveCount(5)
  await expect(page.getByRole('navigation').getByRole('button', { name: 'Review guidelines', exact: true })).toHaveAttribute('aria-current', 'page')
  const checklist = page.getByRole('link', { name: 'Checklist link for creative' })
  await checklist.click()
  await page.goto("./?guidelines&prepared")
  await expect(page.getByRole('heading', { name: 'Review guidelines', exact: true })).toBeVisible()
  await page.getByRole('navigation').getByRole('button', { name: /^All submissions/ }).click()
  await expect(page.getByRole('heading', { name: 'All submissions', exact: true })).toBeVisible()
  await page.locator('.sidebar .brand').click()
  await expect(page.getByRole('heading', { name: 'Ready on the first pass' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Approve v1 & notify Sofia' })).toBeVisible()
  await page.getByRole('button', { name: 'New submission', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'All submissions', exact: true })).toBeVisible()
})

test('mobile navigation exposes the full checklist without horizontal overflow', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 568 })
  await page.goto('./')
  const guidelines = page.getByRole('button', { name: 'Review guidelines', exact: true })
  await expect(guidelines).toBeInViewport({ ratio: 1 })
  await guidelines.click()
  await expect(page.getByRole('heading', { name: 'Review guidelines', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320)
  await page.getByRole('button', { name: 'Open navigation' }).click()
  await page.getByRole('dialog').getByRole('button', { name: /^Review queue/ }).click()
  await page.getByRole('button', { name: 'Open walkthrough' }).click()
  await expect(page.getByRole('heading', { name: 'Marketing review' })).toBeVisible()
  await page.getByRole('button', { name: 'All submissions', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'All submissions', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Open navigation' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Review guidelines', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Review guidelines', exact: true })).toBeFocused()
  await expect(page.locator('.guidelines-checklist > li')).toHaveCount(5)
})
